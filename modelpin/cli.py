#: "no scenarios in 'examples/scenarios'" never said *who* asked for that path.
_SOURCE_LABEL = {
    "flag": "from --scenarios-dir",
    "config": "from scenarios_dir: in modelpin.yaml",
    "default": "the built-in default",
    "suite": "from --suite-dir",
}
_REPO_URL = "https://github.com/samarthputhraya/modelpin"


def _dir_state(p: Path) -> str:
    """Which of the states that `load_scenarios()` collapses into `[]` are we actually in?"""
    if not p.exists():
        return "that directory does not exist"
    if not p.is_dir():
        return "that path is a file, not a directory"
    jsons = sorted(p.glob("*.json"))
    if not jsons:
        return "it exists but contains no .json files"
    if all(f.name in _RESERVED_IN_DIR for f in jsons):
        names = ", ".join(f.name for f in jsons)
        return f"it contains only reserved files ({names}) and no scenario files"
    return "no .json file there loaded as a scenario"


def _init_target(config_path: str) -> Optional[Path]:
    """The scenarios dir `modelpin init` would actually create here, or None if unknowable."""
    try:
        sub = load_config(config_path).scenarios_dir if Path(config_path).exists() else "scenarios"
    except ConfigError:
        return None
    return (Path.cwd() / sub).resolve()


def _demo_hint(resolved: Path) -> str:
    """A generated demo sitting right next to the user is almost always what they meant.

    Without this, forgetting `cd modelpin-demo` sends a deliberately key-less user down the
    `modelpin init` path, which scaffolds a REAL provider config -- and the next command then
    demands a billed OPENAI_API_KEY, contradicting the "no API key" promise they just read.
    """
    for base in (Path.cwd(), resolved.parent):
        candidate = base / DEMO_DIRNAME
        if (candidate / DEMO_FIXTURES).is_file():
            return f"There is an offline demo right here: `cd {DEMO_DIRNAME}` first, then re-run. "
    return ""


def _scenarios_remedy(resolved: Path, source: str, config_path: str) -> str:
    """Advice that is TRUE in this state. `modelpin init` is only named when it would create
    exactly this path — otherwise the user follows it, succeeds, retries, and loops."""
    if source == "suite":
        return (
            "`modelpin init` does not create suite directories. The open public suite ships in "
            f"the repo, not in the wheel: clone {_REPO_URL} and pass "
            "--suite-dir <checkout>/examples/report-suite."
        )
    if resolved == _init_target(config_path):
        return _demo_hint(resolved) + (
            "Run `modelpin init` to scaffold it with a starter scenario, or "
            "`modelpin init --demo` "
            "for a runnable offline demo."
        )
    if source == "flag":
        return (
            "`modelpin init` will NOT create this path. Either add scenario *.json files there, "
            "or drop --scenarios-dir to use the directory from modelpin.yaml."
        )
    return (
        "`modelpin init` scaffolds the directory named by scenarios_dir: in modelpin.yaml, "
        "is not this path. Either add scenario *.json files here, or fix scenarios_dir:."
    )


def _fail_no_scenarios(raw: str, source: str, config_path: str) -> NoReturn:
    resolved = Path(raw).resolve()
    # _rich_escape: _fail() prints through Rich markup, so a path containing '[' would
    # otherwise be swallowed as a style tag and corrupt the very message meant to unstick
    # the user.
    _fail(
        f"no scenarios found in {_rich_escape(str(resolved))} ({_SOURCE_LABEL[source]}) -\n"
        f"       {_dir_state(Path(raw))}.\n"
        f"       {_scenarios_remedy(resolved, source, config_path)}"
    )


def _load_scenarios_or_fail(
    scenarios_dir: str, *, source: str, config_path: str = "modelpin.yaml"
) -> list[Scenario]:
    try:
        scenarios = load_scenarios(scenarios_dir)
    except ScenarioError as exc:
        _fail(str(exc))
    if not scenarios:
        _fail_no_scenarios(scenarios_dir, source, config_path)
    return scenarios


def _scenarios_source(scenarios_dir: Optional[str], config_path: str) -> str:
    """Where the scenarios directory came from, for the error message to quote back."""
    if scenarios_dir:
        return "flag"
    return "config" if Path(config_path).exists() else "default"


def _resolve_provider(provider: Optional[str], cfg: ModelpinConfig) -> str:
    return provider or (cfg.providers[0] if cfg.providers else DEFAULT_PROVIDER)


def _resolve_runs(
    runs: Optional[int],
    cfg: ModelpinConfig,
    *,
    mode: str = "strict",
    baseline_sizes: Sequence[int] | None = None,
) -> int:
    n = cfg.runs if runs is None else runs  # an explicit --runs 0 must hit the floor, not coerce
    if n < MIN_RUNS:
        _fail(
            f"--runs must be >= {MIN_RUNS}: the diff compares run *distributions*, and "
            f"a single run can't form one (got {n})."
        )
    # ADR-0019 discloses the run SIZE before a command spends. A size that cannot reach
    # ALPHA is the same disclosure one level up: the user is about to pay for a run that is
    # structurally incapable of reporting a regression, and "less power" does not say that.
    # [M] MP-55: the shipped demo at `--runs 2` printed `OK 4 scenario(s) unchanged`, exit 0,
    # and wrote "looks safe to adopt" -- where the SAME fixtures at `--runs 5` find two
    # regressions and a minor.
    #
    # Priced on BOTH sides and on the MODE, or the warning becomes the very defect it exists
    # to prevent. [M] Pricing it on the candidate alone asserted "this run cannot report a
    # regression" over `baseline --runs 5` + `check --runs 2` -- an invocation that then
    # reported two regressions and exited 1, because the real 5v2 floor is 0.047619, below
    # ALPHA. [M] And the distribution floor only gates the tool/argument signals under the
    # EQUIVALENCE modes; the directional ones route through the mean statistic
    # (`diff/__init__.py`), so warning about them under `--match subset` was simply false --
    # reproduced firing a `subset` tool-call regression in the same invocation as the warning
    # that said it could not.
    nb = min(baseline_sizes) if baseline_sizes else n
    floor = min_achievable_pvalue_mean(nb, n)
    if floor > ALPHA:
        console.print(
            f"[bold yellow]warning:[/] at {nb} vs {n} runs/side the exact permutation test "
            f"cannot return a p-value below {floor:.3f}, so NO signal can reach p <= {ALPHA}. "
            f"[bold]This run cannot report a regression[/], whatever the models do. "
            f"Use --runs {RECOMMENDED_RUNS}."
        )
    elif mode in EQUIVALENCE_MODES and min_achievable_pvalue_distribution(nb, n) > ALPHA:
        dist_floor = min_achievable_pvalue_distribution(nb, n)
        console.print(
            f"[yellow]warning:[/] at {nb} vs {n} runs/side the tool-call and argument signals "
            f"cannot reach p <= {ALPHA} under `{mode}` (their floor is {dist_floor:.3f}). The "
            f"one-sided signals — refusal, format drift and the semantic judge — reach "
            f"{floor:.3f}. Use --runs {RECOMMENDED_RUNS}."
        )
    elif n < RECOMMENDED_RUNS:
        console.print(
            f"[yellow]warning:[/] only {n} runs/scenario; {RECOMMENDED_RUNS}+ gives the "
            "statistical diff real power and a lower false-positive rate."
        )
    return n


def _resolve_match_mode(mode: str) -> str:
    if mode not in VALID_MATCH_MODES:
        _fail(f"--match must be one of {', '.join(VALID_MATCH_MODES)} (got {mode!r}).")
    return mode


