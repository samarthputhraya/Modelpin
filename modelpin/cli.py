def _fail(message: str) -> NoReturn:
    console.print(f"[red]error:[/] {message}")
    raise typer.Exit(code=1)


def _adapter(provider: str, fixtures: Optional[str]) -> ProviderAdapter:
    try:
        if provider == "fake":
            return FakeProvider.from_fixtures(fixtures) if fixtures else FakeProvider()
        return get_adapter(provider)
    except FileNotFoundError as exc:
        _fail(f"fixtures file not found: {exc}")
    except ValueError as exc:  # unknown provider
        _fail(str(exc))


def _unimplemented_msg(provider: str) -> str:
    return (
        f"the {provider!r} adapter isn't implemented yet. Try `--provider fake "
        "--fixtures <file>` to run offline, or pick `--provider openai`."
    )


def _preflight_or_fail(adapter: ProviderAdapter, provider: str) -> None:
    """Fail before any tokens are spent if the provider isn't ready (key/SDK)."""
    try:
        adapter.preflight()
    except ProviderError as exc:
        _fail(str(exc))


def _guard_replay(provider: str, fn):
    """Run a replay step, converting adapter failures into friendly CLI errors."""
    try:
        return fn()
    except NotImplementedError:
        _fail(_unimplemented_msg(provider))
    except ProviderError as exc:
        _fail(str(exc))


def _replay_plan(
    count: int,
    src_dir: str,
    runs: int,
    provider: str,
    judge_model: Optional[str],
    sides: int = 1,
    ref_runs: Optional[int] = None,
) -> str:
    """Describe the size of the run that is ABOUT to happen, for the pre-spend line.

    The `>=` is load-bearing and must not be "tidied" into an exact count: one replay is one
    `adapter.run()`, but an agent scenario's replay drives a tool loop of up to
    `MAX_TOOL_TURNS` completions, so replays FLOOR the paid calls and never cap them.
    ADR-0019 governs this contract, including why `fake` must claim no cost at all.

    `sides` is how many models are replayed LIVE: 1 for `baseline` (which WRITES the store
    via `save_baseline` and has no reference side at all) and for `check` (whose reference
    traces come off disk), and 2 for `report`, which replays `--from` and `--to` both. It
    scales replays and therefore paid calls -- but deliberately NOT the judge axis, because
    `semantic_divergence_flags` scores every run on both sides regardless of where those
    traces came from. [M] MP-70: the same 14-scenario suite queues 70 replays under `check`
    and 140 under `report`. Both disclose `up to 140 judge calls` WHEN the reference side
    holds `runs` traces per scenario; see `ref_runs` below for when `check`'s does not.
    (That ceiling
    is deliberately loose: a real run needs at most 126, because an output identical to the
    modal baseline skips the judge -- `up to` is the honest word for a bound.) Deriving the
    judge count from `replays` would overstate `report`'s judge bill 2x -- the false-claim
    defect ADR-0019 rejects, merely pointed the other way.

    `ref_runs` is the TOTAL number of reference-side runs the judge will score, summed
    over the scenarios being replayed. It exists because `count * runs` is the CANDIDATE
    side's size and only accidentally the reference side's. `check` reads its reference
    traces off disk, and `load_baseline` returns however many runs were RECORDED --
    `--runs` bounds the replay, never the recording -- so a baseline taken at `--runs 20`
    and checked at `--runs 5` scores 20 reference runs, not 5. [M] MP-72: that pairing
    issues 24 judge calls for ONE scenario against a `2 x 1 x 5 = 10` disclosure. Left as
    None the reference side is assumed to be `count * runs`: VACUOUS for `baseline` (the
    judge clause never renders, so the value is unreachable) and EXACT for `report` (both
    sides come from `replay()`, so both are `runs` by construction) -- hence those two
    render byte-identically to before.
    Under-disclosing a paid axis is the same ADR-0019 violation as claiming an exact
    count, merely pointed the other way again.
    """
    replays = count * runs * sides
    plan = f"{count} scenario(s) from {src_dir}"
    if sides > 1:
        plan += f" x {sides} models"
    plan += f" -> {replays} replays"
    if provider == "fake":
        return plan  # canned traces, no network, nothing billed
    plan += f", >={replays} paid calls"
    if judge_model:
        judged = (count * runs if ref_runs is None else ref_runs) + count * runs
        plan += f" + up to {judged} judge calls"
    return plan


def _build_judge(provider: str, cfg: ModelpinConfig, to_model: str | None = None):
    """Construct + preflight the semantic LLM-judge if configured. Returns None when no
    judge_model is set or the run is offline (fake), so the diff stays purely structural."""
    if not cfg.judge_model or provider == "fake":
        return None
    try:
        from modelpin.judge import build_judge

        from modelpin.judge import infer_judge_provider

        # The judge is independent of the models being compared, so a cross-vendor check
        # (e.g. google vs openai) can still judge. MP-143: which HOST runs it is resolved
        # explicitly -- `judge_provider:` first, then an unambiguous model-id prefix, then
        # the REPLAY provider as the last resort. That last step is what makes the common
        # zero-config case work for a Groq-only user, who otherwise had no channel that
        # reads meaning at all; it is never a guess between two hosts, and the host is
        # printed below so the choice is visible before any of the user's money is spent.
        host = cfg.judge_provider or infer_judge_provider(cfg.judge_model) or provider
        judge = build_judge(cfg.judge_model, provider=host)
        judge.preflight()
    except (ProviderError, ImportError) as exc:
        _fail(f"semantic judge ({cfg.judge_model!r}): {exc}")
    console.print(f"[dim]semantic judge: {cfg.judge_model} on {host}[/]")
    if cfg.judge_model == to_model:
        # Not an error -- it can be a deliberate, cheap choice -- but a model judging its own
        # output is not an independent reading of it, and the north-star metric is the FP
        # RATE of what we publish. Say so once, at the point of choosing.
        console.print(
            "[yellow]note:[/] the judge model is the model being checked, so the semantic "
            "channel is not an independent reading. Prefer a different judge model."
        )
    return judge


