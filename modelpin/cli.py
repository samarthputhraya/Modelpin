def _resolve_runs(
    runs: Optional[int],
    cfg: ModelpinConfig,
    *,
    mode: str = "strict",
    baseline_sizes: Sequence[int] | None = None,
) -> int:
    n = cfg.runs if runs is None else runs  # an explicit --runs 0 must hit the floor, not coerce
    if n < MIN_RUNS:
        _fail(
            f"--runs must be >= {MIN_RUNS}: the diff compares run *distributions*, and "
            f"a single run can't form one (got {n})."
        )
    # ADR-0019 discloses the run SIZE before a command spends. A size that cannot reach
    # ALPHA is the same disclosure one level up: the user is about to pay for a run that is
    # structurally incapable of reporting a regression, and "less power" does not say that.
    # [M] MP-55: the shipped demo at `--runs 2` printed `OK 4 scenario(s) unchanged`, exit 0,
    # and wrote "looks safe to adopt" -- where the SAME fixtures at `--runs 5` find two
    # regressions and a minor.
    #
    # Priced on BOTH sides and on the MODE, or the warning becomes the very defect it exists
    # to prevent. [M] Pricing it on the candidate alone asserted "this run cannot report a
    # regression" over `baseline --runs 5` + `check --runs 2` -- an invocation that then
    # reported two regressions and exited 1, because the real 5v2 floor is 0.047619, below
    # ALPHA. [M] And the distribution floor only gates the tool/argument signals under the
    # EQUIVALENCE modes; the directional ones route through the mean statistic
    # (`diff/__init__.py`), so warning about them under `--match subset` was simply false --
    # reproduced firing a `subset` tool-call regression in the same invocation as the warning
    # that said it could not.
    nb = min(baseline_sizes) if baseline_sizes else n
    floor = min_achievable_pvalue_mean(nb, n)
    if floor > ALPHA:
        console.print(
            f"[bold yellow]warning:[/] at {nb} vs {n} runs/side the exact permutation test "
            f"cannot return a p-value below {floor:.3f}, so NO signal can reach p <= {ALPHA}. "
            f"[bold]This run cannot report a regression[/], whatever the models do. "
            f"Use --runs {RECOMMENDED_RUNS}."
        )
    elif mode in EQUIVALENCE_MODES and min_achievable_pvalue_distribution(nb, n) > ALPHA:
        dist_floor = min_achievable_pvalue_distribution(nb, n)
        console.print(
            f"[yellow]warning:[/] at {nb} vs {n} runs/side the tool-call and argument signals "
            f"cannot reach p <= {ALPHA} under `{mode}` (their floor is {dist_floor:.3f}). The "
            f"one-sided signals — refusal, format drift and the semantic judge — reach "
            f"{floor:.3f}. Use --runs {RECOMMENDED_RUNS}."
        )
    elif n < RECOMMENDED_RUNS:
        console.print(
            f"[yellow]warning:[/] only {n} runs/scenario; {RECOMMENDED_RUNS}+ gives the "
            "statistical diff real power and a lower false-positive rate."
        )
    return n


def _cannot_reach_alpha(nb: int, nc: int, mode: str) -> bool:
    """True when NO signal could have reached ``p <= ALPHA`` at these run counts (MP-55).

    Shared by ``check`` and ``report`` (MP-140) so one rule produces the disclosure on
    every surface. ``check`` reads ``nb`` off the STORED baseline, which can hold a
    different depth than ``--runs`` gives the candidate; ``report`` replays both sides
    itself, so ``nb == nc``.

    Priced on both sides and on the MODE. `[M]` The narrower trap is a MORE confident false
    clearance than the blunt one: at 3v3 `strict` the demo's ``refund_request`` -- whose
    only change is the tool-call trajectory -- rendered "no behavioral change" and "looks
    safe to adopt", while N=4 on identical fixtures reports a regression. The equivalence
    modes route the tool and argument signals through the two-sided test, whose floor is
    higher; the directional signals do not, so applying it under `subset`/`superset` would
    assert blindness about signals that can and do fire.
    """
    if min_achievable_pvalue_mean(nb, nc) > ALPHA:
        return True  # no signal at all could have fired
    return mode in EQUIVALENCE_MODES and min_achievable_pvalue_distribution(nb, nc) > ALPHA


def _exercised_tools(*sides: Sequence[Trace]) -> bool:
    """Did a tool actually get CALLED, on any run of any side?

    MP-159. This is the question the tool channel's liveness turns on, and
    ``Trace.tool_calls`` (`models.py`) is the only thing that can answer it. `[M]` The
    diff signal cannot: ``DiffSignals.tool_call_match`` reads **1.00** -- a perfect match --
    between two sides that each called zero tools, so a signal-based proxy would report the
    channel live in exactly the case it is dead.
    """
    return any(t.tool_calls for side in sides for t in side)


def _publish_report(markdown: str, store_dir: str, from_model: str, to: str) -> list[str]:
    """Write `last-report.md` and its durable archive copy; RETURN the notes to print.

    MP-160 extracted this because the zero-comparison exit paths did not write one. `[M]`
    A run whose scenarios are all un-baselined exits EXIT_UNMEASURED, and it used to leave
    the PREVIOUS run's `last-report.md` untouched -- which `action.yml` posts whenever it
    exists, independent of the exit code. CI published a stale verdict under a failing run.

    It returns its console notes rather than printing them so the CALLER can write the
    artifact first and print afterwards. `[M] 2026-09-01` that ordering is load-bearing: the
    console summary can raise `UnicodeEncodeError` on a cp1252 terminal, and while it printed
    first a crash there cost the artifact entirely.

    MP-150's write order is preserved: the stable path CI reads is written FIRST and the
    archive second, so if only one write can succeed it is the one CI reads.
    """
    notes: list[str] = []
    report_path = Path(store_dir) / "last-report.md"
    try:
        report_path.parent.mkdir(parents=True, exist_ok=True)
        report_path.write_text(markdown, encoding="utf-8")
        notes.append(
            f"[dim]PR-style Markdown report written to {_rich_escape(str(report_path))}[/]"
        )
    except OSError as exc:
        notes.append(
            f"[yellow]warning:[/] could not write report to "
            f"{_rich_escape(str(report_path))}: {_rich_escape(str(exc))}"
        )
        return notes
    try:
        archived = _archive_path(Path(store_dir), from_model, to)
        archived.write_text(markdown, encoding="utf-8")
        notes.append(f"[dim]archived for citation: {_rich_escape(str(archived))}[/]")
    except OSError as exc:
        notes.append(f"[yellow]warning:[/] could not archive the report: {_rich_escape(str(exc))}")
    return notes


def _channel_census(
    scenarios: Sequence[Scenario],
    judge: object | None,
    prov: str,
    *,
    tool_active: AbstractSet[str],
) -> ChannelCensus:
    """MP-138's census, read off the scenarios that were actually COMPARED (MP-140).

    Shared by ``check`` and ``report``. The judge half is read off the config; the TOOL half
    is read off the RECORDED TRACES, carried in by ``tool_active`` -- the ids whose runs
    actually called a tool.

    MP-159 replaced a declaration read with that trace read, for the reason this module
    already applies to refusal one screen below. `[M] 2026-08-31`, reproduced end to end on
    byte-identical fixtures: a scenario declaring one `tools` entry that NO run on either
    side ever called flipped `could not measure ... NOT cleared on content` into
    `no behavioral change ... looks safe to adopt` -- over a baseline of *"FRAUD DETECTED:
    block this transaction"* against a candidate of *"Looks fine, approve it. asdf qwerty
    zzzz garbage."* A declared tool that nothing calls sits in exactly the position
    ``hard_content_channels`` already excludes refusal for: it can only fire if the
    candidate STARTS calling tools, so a confident wrong answer never touches it. Counting
    it restored the false comfort this census exists to remove -- and the disclosure's own
    printed remedy, *"add `tools`"*, was what bought the green.

    ``tool_active`` is keyword-only with NO default on purpose. A caller that cannot supply
    traces must be made to say so at the call site: defaulting to "none exercised" would be
    safe in DIRECTION but would put a false sentence -- "no run called a tool" -- inside the
    disclosure that exists to be honest, which is the same defect one surface over.

    `[M]` The judge reason is computed HERE from the provider rather than inferred from
    ``judge is None`` downstream: the offline `fake` provider disables the judge regardless
    of config (``_build_judge``), so inferring "no judge_model configured" would put a false
    statement inside the disclosure that exists to be honest.
    """
    judge_enabled = judge is not None

    # MP-141. A scenario's OWN content coverage: the judge is suite-wide (one config key),
    # but a tool call happens per scenario, so with the judge off a scenario whose runs
    # called nothing has no CI-failing channel that reads content -- whatever its neighbours
    # did. MP-159 is the second half of that sentence: the trace must show a CALL, not just
    # the suite a declaration.
    #
    # BOTH halves are required, and the conjunction is the whole point of the shape. `[M]`
    # FP review BLOCKED the first cut, which tested `s.id in tool_active` alone: a scenario
    # with NO `tools` key whose traces nevertheless carry `tool_calls` went from HEAD's
    # "NOT cleared on content" to "looks safe to adopt" over the same content inversion --
    # MP-159's own defect, arriving through the other door in the same commit. That state is
    # not reachable from a live replay (both live adapters gate the request `tools` on
    # `scenario.input["tools"]`), but it is reachable from a hand-edited `traces.json` --
    # which `README.md` explicitly invites -- and from a baseline recorded before the `tools`
    # key was removed, since the store round-trips `tool_calls` faithfully.
    #
    # Requiring both makes the new blind set a SUPERSET of the old one for every input, so
    # this change can only ever withhold a clearance HEAD granted, never grant one HEAD
    # withheld. That monotonicity is the property that makes it safe to ship without new
    # calibration, and it is the same one MP-141 claimed for itself.
    def _tool_live(s: Scenario) -> bool:
        return bool(s.input.get("tools")) and s.id in tool_active

    blind = () if judge_enabled else tuple(s.id for s in scenarios if not _tool_live(s))
    return ChannelCensus(
        tools_exercised=any(_tool_live(s) for s in scenarios),
        # MP-159. The scenarios that ASKED for the tool channel and did not get it. Only the
        # remedy wording reads this, and that is the point: telling a user to "add `tools`"
        # when they already have is not merely useless, it is the advice that bought the
        # false clearance in the first place.
        declared_unused_tools=tuple(
            s.id for s in scenarios if s.input.get("tools") and s.id not in tool_active
        ),
        # MP-141. Read the fields the ENGINE reads, not the presence of an `Assertion`
        # object. `[M]` `diff/__init__.py` consults only `must_contain` / `must_not_contain`
        # (`structural.py::violates_text_assertions`). MP-147 deleted the two fields that
        # were read by nothing, so today an `Assertion` with neither live field set is an
        # EMPTY one -- which is still not coverage, and this check is still what says so.
        # `[M]` The shipped demo relied on the difference: `angry_customer` once carried an
        # `Assertion` whose only field was dead, and the old test counted it as armed in the
        # suite a brand-new user runs first.
        assertions_declared=any(
            s.assertions is not None
            and (s.assertions.must_contain or s.assertions.must_not_contain)
            for s in scenarios
        ),
        judge_enabled=judge_enabled,
        judge_off_reason=(
            "disabled on the offline `fake` provider"
            if prov == "fake"
            else "no `judge_model` configured"
        ),
        blind_scenarios=blind,
        compared=len(scenarios),
    )


def _resolve_match_mode(mode: str) -> str:
    if mode not in VALID_MATCH_MODES:
        _fail(f"--match must be one of {', '.join(VALID_MATCH_MODES)} (got {mode!r}).")
    return mode


